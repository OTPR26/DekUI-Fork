#!/usr/bin/env python3
"""Generate the five classic Double Time questions from the native choice format.
Only emits a guarded C++ replacement table; never modifies game assets.
"""
from dialogue_recipe import recipe
import argparse
from pathlib import Path
from double_prices import decode, encode, messages

ROOT = Path(__file__).resolve().parents[2]
DESTINATIONS = (
    'Night of the 1st Day', 'Dawn of the 2nd Day', 'Night of the 2nd Day',
    'Dawn of the Final Day', 'Night of the Final Day',
)

def generate(data):
    source = messages(data)
    original = source[0x1b8a]
    assert len(original) == 84
    assert (47,2) in decode(original), 'Expected native two-choice message'
    variants = []
    for destination in DESTINATIONS:
        # Start the red destination on line two. End directly after No:
        # the native message reset initializes colors for the next textbox.
        # Omitting the unused final color reset keeps all variants in 84 bytes.
        tokens = ['Proceed to the', (1,), (58, 1), destination, (58, 11), '?',
                  (1,), (58, 2), (47, 2), 'Yes', (1,), 'No', (0,)]
        raw = encode(tokens)
        assert decode(raw) == tokens and len(raw) <= len(original)
        variants.append(raw.ljust(len(original), b'\0'))
    output = ('// SPDX-License-Identifier: GPL-2.0-or-later\n'
              '// Generated by tools/mm3d/classic_double_time_text.py.\n'
              '#pragma once\n#include <array>\n#include "mm3d/dialogue_recipe.h"\n'
              'namespace MM3D::ClassicDoubleTime {\n')
    output += f'inline constexpr DialogueText::Recipe OriginalText{recipe(original)};\n'
    output += 'inline constexpr std::array<DialogueText::Recipe,5> Questions{{\n'
    output += ''.join(f'    {recipe(original,raw)},\n' for raw in variants)
    return output + '}};\n}\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT/'resources/mm3d/project-restoration/romfs/message/us/use.gmsg')
    parser.add_argument('--output', type=Path, default=ROOT/'src/mm3d/classic_double_time_text.h')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate(args.source.read_bytes())
    if args.check:
        assert args.output.read_text() == output, 'Generated text header is stale'
    else:
        args.output.write_text(output)
    print('Five red destinations, native Yes/No controls, capacity, and Final Night wording verified.')
