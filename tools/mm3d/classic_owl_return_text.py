#!/usr/bin/env python3
"""Generate authored resume notices as sparse edits against user-owned text."""
from pathlib import Path
import argparse
import single_screen_text as text
from dialogue_recipe import recipe
from classic_owl_text import CAPACITY, PROMPT

def dialogue():
    first = 'Your temporary save has been loaded.\nYour adventure continues here.'
    second = 'Save again before leaving the game\nto keep your new progress.'
    return ([(0x27,)] + text.markup(first) + [(0x28,), (0x31,1), (2,), (0x27,)] +
            text.markup(second) + [(0x28,), (0x31,0), (0,)])

def header(source):
    original=text.messages(source)[PROMPT].ljust(CAPACITY,b'\0')
    raw=text.encode(dialogue())
    assert len(raw)<=CAPACITY and text.decode(raw)==dialogue()
    return ('// SPDX-License-Identifier: GPL-2.0-or-later\n'
            '// Generated by tools/mm3d/classic_owl_return_text.py. Do not edit.\n'
            '#pragma once\n#include "mm3d/dialogue_recipe.h"\n'
            'namespace MM3D::SingleScreenText {\n'
            f'inline constexpr DialogueText::Recipe ClassicOwlReturnText{recipe(original,raw)};\n'
            f'inline constexpr std::uint64_t ClassicOwlReturnHash=0x{text.fnv(raw.ljust(CAPACITY,b"\0")):016x}ULL;\n'
            '}\n')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source',type=Path)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    args.output.write_text(header(args.source.read_bytes()))
