#!/usr/bin/env python3
"""Generate the two instant classic-resume pages with the native byte-text codec."""
from pathlib import Path
import single_screen_text as text

def dialogue():
    first = 'Ye who hold the sacred sword...\nYe have returned to the appointed\nspot.'
    second = ('If you wish to {Color:1}interrupt{Color:11} your adventure\n'
              '({Color:1}game{Color:11}) again, {Color:1}speak to me{Color:11}, the one that\n'
              'you have marked to prove your\nencounter.')
    return ([(0x27,)] + text.markup(first) + [(0x28,), (0x31,1), (2,), (0x27,)] +
            text.markup(second) + [(0x28,), (0x31,0), (0,)])

def header():
    tokens = dialogue()
    raw = text.encode(tokens)
    assert text.decode(raw) == tokens
    assert tokens.count((2,)) == 1 and tokens.count((0x27,)) == 2
    assert len(raw) <= 1024
    literal = ''.join('\\%03o' % b for b in raw)
    return ('// SPDX-License-Identifier: GPL-2.0-or-later\n'
            '// Generated by tools/mm3d/classic_owl_return_text.py. Do not edit.\n'
            '#pragma once\n#include <string_view>\n#include <cstdint>\n'
            'namespace MM3D::SingleScreenText {\n'
            f'inline constexpr std::string_view ClassicOwlReturnText{{"{literal}",{len(raw)}}};\n'
            f'inline constexpr std::uint64_t ClassicOwlReturnHash=0x{text.fnv(raw+bytes(1024-len(raw))):016x}ULL;\n'
            '}\n')

if __name__ == '__main__':
    (Path(__file__).resolve().parents[2] / 'src/mm3d/classic_owl_return_text.h').write_text(header())
