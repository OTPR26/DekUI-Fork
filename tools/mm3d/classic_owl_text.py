#!/usr/bin/env python3
"""Prepare expanded owl-prompt storage for an isolated USA English test profile.
No message IDs are borrowed. All other entries and payloads stay byte-identical.
The native prompt remains the default; the emulator toggles the longer wording.
"""
import argparse
import struct
from pathlib import Path
import single_screen_text as text

PROMPT = 0x0C01
CAPACITY = 1024

def dialogue():
    # 27/28: instant text on/off; 31/2: wait then next page; 2f: choices.
    pages = [
        "You can {Color:1}save{Color:11} your {Color:1}progress{Color:11} and\n"
        "{Color:1}quit{Color:11} here. When you reselect your file,\n"
        "a glowing icon will appear by your file\nname.",
        "This indicates that the next time you\nreopen your file, you'll resume playing\n"
        "at this {Color:1}very place{Color:11} and {Color:1}time{Color:11} with your\n"
        "{Color:1}current status{Color:11}.",
        "{Color:1}Warning:{Color:11} If you reopen this\n"
        "file, then reset without saving at\n"
        "an owl statue, you'll lose the\n"
        "progress you've saved here...",
        "The next time you open the file,\n"
        "you'll restart at Day One with the\n"
        "status you had when you last saved\n"
        "using The Song of Time.",
        "{Color:1}Save{Color:11} your {Color:1}progress{Color:11} up to this point\n"
        "and {Color:1}quit{Color:11} playing?",
    ]
    tokens = []
    for page in pages[:-1]:
        tokens += [(0x27,)] + text.markup(page) + [(0x28,), (0x31, 1), (2,), (0x3a, 11)]
    tokens += text.markup(pages[-1])
    tokens += [(1,), (0x3a, 2), (0x2f, 2), 'Yes', (1,), 'No', (0x3a, 11), (0,)]
    return tokens

def prepare(data):
    original = text.messages(data)
    raw = original[PROMPT]
    expected = text.encode([(0x3a,0),(0x3a,1),'Save',(0x3a,0),' your progress ',
                            (0x3a,11),'up to this point?',(1,),(0x3a,2),(0x2f,2),
                            'Yes',(1,),'No',(0x3a,11),(0,)])
    if raw != expected:
        raise ValueError('Unsupported owl prompt; archive left untouched')
    tokens = dialogue()
    replacement = text.encode(tokens)
    assert len(replacement) <= CAPACITY
    text.ARGS[0x2f] = 1
    assert text.decode(replacement) == tokens
    padded = raw + bytes(CAPACITY-len(raw))
    out = bytearray(data)
    if len(out)&1: out.append(0)
    offset = len(out)
    out.extend(padded)
    count = struct.unpack_from('<I',data,8)[0]
    for i in range(count):
        at = 16+20*i
        if struct.unpack_from('<H',data,at)[0] == PROMPT:
            struct.pack_into('<II',out,at+12,offset,CAPACITY)
            break
    after = text.messages(out)
    assert all(after[i] == v for i,v in original.items() if i != PROMPT)
    row = (PROMPT,CAPACITY,text.fnv(padded),replacement,tokens,padded)
    header = text.header([row])
    # Share the existing replacement type and guarded writer.
    header = header.replace('Generated by tools/mm3d/single_screen_text.py.',
                            'Generated by tools/mm3d/classic_owl_text.py.')
    header = '\n'.join(l for l in header.splitlines() if not l.startswith('struct Replacement'))
    header = header.replace('Replacements{{','ClassicOwlReplacements{{')
    pages = 1 + tokens.count((2,))
    header = header.replace('namespace MM3D::SingleScreenText {',
        f'namespace MM3D::SingleScreenText {{\ninline constexpr unsigned ClassicOwlPageCount = {pages};')
    return bytes(out),header+'\n',len(replacement)

if __name__ == '__main__':
    p=argparse.ArgumentParser()
    p.add_argument('source',type=Path);p.add_argument('output',type=Path)
    p.add_argument('--header',type=Path,required=True)
    a=p.parse_args()
    out,h,n=prepare(a.source.read_bytes())
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_bytes(out);a.header.write_text(h)
    print(f'Owl dialogue: {n}/{CAPACITY} bytes; every other message verified unchanged')
