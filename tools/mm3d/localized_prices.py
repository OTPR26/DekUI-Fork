#!/usr/bin/env python3
"""Generate guarded localized price edits from the user's supported USA dump."""
import argparse
import json
import re
import struct
from pathlib import Path
from single_screen_text import messages, fnv
from double_prices import decode, encode
ROOT = Path(__file__).resolve().parents[2]
CAPPED = {0x1600,0x1606,0x2afa,0x2b0b,0x06ba,0x06bb,0x06d7,0x06d8}

def compile_localized(data, spec, language, factor, adjustments):
    originals = messages(data, language)
    metadata = {int(x,16) for x in spec['metadata_ids']}
    ids = metadata | {int(x,16) for x in spec['literal_ids']} | {int(x,16) for x in spec['special_literals']}
    entries = {struct.unpack_from('<H',data,16+i*20)[0]:struct.unpack_from('<I',data,20+i*20)[0]
               for i in range(struct.unpack_from('<I',data,8)[0])}
    def scale(mid, value):
        return min(value*factor,500) if mid in CAPPED and value<=500 else value*factor
    rows=[]
    for mid in sorted(ids):
        raw=originals[mid];original=decode(raw);tokens=list(original)
        # Match amounts across line breaks/colour controls, without changing item
        # quantities, scores, prizes, or other numbers in the same message.
        visible='';positions=[]
        for i,t in enumerate(tokens):
            if isinstance(t,str):
                visible+=t;positions += [(i,j) for j in range(len(t))]
            elif t[0] == 1:
                visible+=' ';positions.append(None)
            elif t[0] != 0x3a:
                visible+='|';positions.append(None)
        matches=list(re.finditer(r'\b([0-9][0-9,]*)\s+(?:rubis|rupias?)\b',visible,re.I))
        for match in reversed(matches):
            number=match[1];n=int(number.replace(',',''));value=scale(mid,n)
            if f'{mid:04x}' in spec['special_literals']:
                value=100-10*factor if n==90 else 10*factor if n==10 else n
            locations=positions[match.start(1):match.end(1)]
            assert locations and all(p and p[0]==locations[0][0] for p in locations)
            i,start=locations[0];end=locations[-1][1]+1
            replacement=f'{value:,}' if ',' in number else str(value)
            tokens[i]=tokens[i][:start]+replacement+tokens[i][end:]
        for old,new in adjustments.get('rewrites',{}).get(f'{mid:04x}',{}).items():
            new=new.replace('{factor}',str(factor))
            assert any(isinstance(t,str) and old in t for t in tokens),(hex(mid),old)
            tokens=[t.replace(old,new) if isinstance(t,str) else t for t in tokens]
        if len(encode(tokens))>len(raw):
            for old,new in adjustments.get('shorten',{}).get(f'{mid:04x}',{}).items():
                assert any(isinstance(t,str) and old in t for t in tokens),(hex(mid),old)
                tokens=[t.replace(old,new) if isinstance(t,str) else t for t in tokens]
        if len(encode(tokens))>len(raw):
            compact=[]
            for t in tokens:
                if isinstance(t,tuple) and t[0]==0x3a and compact and isinstance(compact[-1],tuple) and compact[-1][0]==0x3a:compact.pop()
                compact.append(t)
            tokens=compact
        out=encode(tokens)
        if len(out)>len(raw):
            print(f'OVERFLOW {language} {factor} {mid:04x} {len(out)}/{len(raw)} {tokens!r}')
            continue
        flow=lambda ts:[t for t in ts if not isinstance(t,str) and t[0]!=0x3a]
        assert flow(tokens)==flow(original) and decode(out)==tokens
        def lines(ts):
            result=['']
            for token in ts:
                if isinstance(token,str):result[-1]+=token
                elif token[0] in (1,2):result.append('')
                elif token[0]==0x25:result[-1]+='◆'
            return result
        for before,after in zip(lines(original),lines(tokens)):
            # Preserve native long lines; never grow one past the conservative
            # dialogue budget. Actual font widths still need visual validation.
            assert len(after)<=32 or len(after)<=len(before),(language,hex(mid),after)
        value=entries[mid];updated=value
        if mid in metadata:
            for shift in (0,10,20):
                n=(value>>shift)&1023
                if n!=1023:
                    v=scale(mid,n);assert v<1023
                    updated=(updated&~(1023<<shift))|(v<<shift)
        rows.append((mid,raw,out,value,updated))
    if len(rows)!=len(ids):raise ValueError('Localized prices need shortening')
    return rows

def build(source):
    spec=json.loads((ROOT/'resources/mm3d/text/double-prices.json').read_text())
    lines=['// SPDX-License-Identifier: GPL-2.0-or-later','// Generated by tools/mm3d/localized_prices.py. Do not edit.',
           '#pragma once','#include "mm3d/price_text_data.h"','namespace MM3D::Prices {']
    literal=lambda b:'"'+''.join('\\%03o'%x for x in b)+'"'
    for language,name,archive in [(4,'French','usf'),(8,'Spanish','uss')]:
        adjustments=json.loads((ROOT/f'resources/mm3d/text/prices-{name.lower()}.json').read_text())
        data=(source/f'{archive}.gmsg').read_bytes()
        for factor,prefix in [(2,''),(3,'Triple')]:
            rows=compile_localized(data,spec,language,factor,adjustments)
            lines.append(f'inline constexpr std::array<MessageEdit,{len(rows)}> {name}{prefix}Messages{{{{')
            for mid,raw,new,oldmeta,newmeta in rows:
                lines.append(f'{{0x{mid:04x},{{{literal(raw)},{len(raw)}}},{{{literal(new)},{len(new)}}},0x{oldmeta:x},0x{newmeta:x},0x{fnv(raw):x}ULL,0x{fnv(new+bytes(len(raw)-len(new))):x}ULL}},')
            lines.append('}};')
    return '\n'.join(lines+['}',''])

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('source',type=Path);p.add_argument('--header',type=Path,required=True);a=p.parse_args()
    a.header.write_text(build(a.source))
